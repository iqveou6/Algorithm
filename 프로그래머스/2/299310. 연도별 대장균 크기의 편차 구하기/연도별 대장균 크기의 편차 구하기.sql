SELECT B.YEAR, B.SIZE - A.SIZE_OF_COLONY AS YEAR_DEV, A.ID FROM (SELECT YEAR(DIFFERENTIATION_DATE) AS YEAR, MAX(SIZE_OF_COLONY) AS SIZE FROM ECOLI_DATA
GROUP BY YEAR(DIFFERENTIATION_DATE)) AS B
JOIN ECOLI_DATA A ON B.YEAR = YEAR(A.DIFFERENTIATION_DATE)
ORDER BY YEAR(DIFFERENTIATION_DATE) ASC, YEAR_DEV ASC